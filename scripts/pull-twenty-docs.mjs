// Mirrors the Twenty app SDK documentation into docs/twenty/upstream/. The
// directory is gitignored: it is a local reference mirror, not project
// documentation.
//
//   node scripts/pull-twenty-docs.mjs
//
// The page list is the one twenty-native-app/AGENTS.md points at, which is
// the same list the Twenty team publishes for app authors. The dialer uses
// exactly three of those areas, and they are the ones that matter here:
//
//   Logic functions  - 33 of them under src/logic-functions/, each an HTTP
//                      route with httpRouteTriggerSettings
//   Front components - DialerApp, rendered in a Remote-DOM sandbox, which is
//                      why it avoids twenty-ui Tabs and Checkbox
//   Roles            - src/default-role.ts is what logic functions run under
//
// Anything fetched here is reference only. The dialer's own contract is in
// twenty-native-app/CLAUDE.md and the diagrams under docs/diagrams/.

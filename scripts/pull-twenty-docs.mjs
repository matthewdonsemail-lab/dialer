async function main() {
  fs.rmSync(TARGET, { recursive: true, force: true });
  fs.mkdirSync(TARGET, { recursive: true });

  let ok = 0;
  const missing = [];

  // Bounded pool so a slow page cannot stall the run.
  const queue = [...DOC_PAGES];
  const CONCURRENCY = 6;

  async function worker() {
    while (queue.length > 0) {
      const page = queue.shift();
      try {
        const text = await fetchWithRetry(`${BASE}/${page}`);
        const out = path.join(TARGET, page);
        fs.mkdirSync(path.dirname(out), { recursive: true });
        fs.writeFileSync(out, text, 'utf8');
        ok += 1;
        console.log(`  ok    ${page} (${text.length} bytes)`);
      } catch (error) {
        missing.push(page);
        console.log(`  skip  ${page} (${error.message})`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, () => worker()));

  fs.writeFileSync(
    path.join(TARGET, 'README.md'),
    `${INDEX}\nGenerated: ${new Date().toISOString()}\nUnavailable pages: ${
      missing.length ? missing.join(', ') : 'none'
    }\n`,
    'utf8',
  );

  console.log(`\nTwenty mirror: ${ok}/${DOC_PAGES.length} pages fetched into docs/twenty/upstream/ (gitignored).`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

async function main() {
  fs.mkdirSync(TARGET, { recursive: true });

  let ok = 0;
  let failed = 0;
  const missing = [];

  for (const page of DOC_PAGES) {
    try {
      const text = await fetchWithRetry(page.url);
      const out = path.join(TARGET, page.to);
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, text, 'utf8');
      ok += 1;
      console.log(`  ok    ${page.to} (${text.length} bytes)`);
    } catch (error) {
      if (page.optional) {
        missing.push(page.to);
        console.log(`  skip  ${page.to} (${error.message})`);
      } else {
        failed += 1;
        console.error(`  FAIL  ${page.to}: ${error.message}`);
      }
    }
  }

  fs.writeFileSync(
    path.join(TARGET, 'README.md'),
    `${INDEX}\nGenerated: ${new Date().toISOString()}\nOptional pages unavailable: ${
      missing.length ? missing.join(', ') : 'none'
    }\n`,
    'utf8',
  );

  console.log(`\nTelnyx mirror: ${ok} fetched, ${failed} required pages failed, ${missing.length} optional skipped.`);
  console.log(`Written to docs/telnyx/upstream/ (gitignored).`);
  if (failed > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

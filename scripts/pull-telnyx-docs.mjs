//
// What the dialer uses Telnyx for, and which page covers it:
//   SIP over WebRTC registration and INVITE, and the call-control id that
//     comes back on the 200 OK  -> Call Control pages
//   POST /v2/calls/{id}/actions/record_start with transcription
//     -> Call Recording pages
//   GET /v2/recordings/{id} for the expiring download URL
//     -> Call Recording pages
//   Webhook delivery and the events that attach recordings and transcripts
//     -> Webhook pages
//   Messaging, for the SMS half of the prospect outreach flow

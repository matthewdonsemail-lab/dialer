// Emits the generated Twenty GraphQL client into packages/shared so the
// Express backend and the Vite SPA share one typed surface without
// depending on twenty-client-sdk or hand-rolled REST wrappers.
//
// Source: introspection of the live workspace (TWENTY_BASE_URL +
// TWENTY_API_KEY from the repo .env.local, process.env wins). Regenerate
// whenever Twenty custom objects/fields change, and commit the result.
//
// Adapted from twenty-coach (`packages/twenty-app/scripts/emit-api-client.mjs`),
// which reads the same SDL from `twenty apply` output instead of introspection.
//
// Usage: bun run api:client [--check]
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { buildClientSchema, getIntrospectionQuery, printSchema } from "graphql";
import { generateCoreClientFromSchema } from "twenty-client-sdk/generate";

const here = dirname(fileURLToPath(import.meta.url));
const TARGET_DIR = join(here, "../src/generated/client");
const HEADER = `// @generated by \`bun run api:client\` — do not edit by hand.
// Source: live workspace GraphQL introspection.\n`;

async function loadEnv() {
  const merged = { ...process.env };
  const dotEnv = join(here, "../../../.env.local");
  const raw = await readFile(dotEnv, "utf8").catch(() => "");
  for (const line of raw.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const i = trimmed.indexOf("=");
    const key = trimmed.slice(0, i);
    if (!(key in merged)) merged[key] = trimmed.slice(i + 1);
  }
  return merged;
}

const isSource = (name) => name.endsWith(".ts") || name.endsWith(".tsx");

// genql emits extensionless relative specifiers (including directory
// imports like `./runtime`), which Node's ESM loader rejects. Rewrite each
// to the exact `./x/index.js` or `./x.js` it refers to.
const fixImportsFor = (files) => (content, fileDir) => {
  let out = "";
  let i = 0;
  const pattern = /(["'])((?:\.\.?\/)[A-Za-z0-9_\-./]+)\1/g;
  for (let match; (match = pattern.exec(content)) !== null; ) {
    const [whole, quote, spec] = match;
    const tail = spec.replace(/^\.\//, "");
    const target = fileDir ? `${fileDir}/${tail}` : tail;
    let fixed = whole;
    if (files.has(target)) {
      const ext = spec.match(/\.tsx?$/);
      fixed = `${quote}${ext ? spec.slice(0, -ext[0].length) + ".js" : spec + ".js"}${quote}`;
    } else if (files.has(`${target}/index`)) fixed = `${quote}${spec}/index.js${quote}`;
    out += content.slice(i, match.index) + fixed;
    i = match.index + whole.length;
    if (match.index === pattern.lastIndex) pattern.lastIndex++;
  }
  return out + content.slice(i);
};

const collect = async (dir, base, pairs) => {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      await collect(path, base, pairs);
    } else if (isSource(entry.name)) {
      const name = relative(base, path).split("\\").join("/");
      pairs.push([name, HEADER + (await readFile(path, "utf8"))]);
    }
  }
  return pairs;
};

const prepare = (pairs) => {
  const files = new Set(pairs.map(([name]) => name.replace(/\.tsx?$/, "")));
  return pairs
    .map(([name, raw]) => {
      let content = raw;
      // types.ts comes out without the generator's @ts-nocheck, and its
      // default-exported type map is too large for declaration emit to
      // serialize (TS7056 — an emit-time error @ts-nocheck cannot suppress).
      // An explicit `any` annotation keeps the value usable (index.ts only
      // ever passes it as `any` to linkTypeMap) while making the emitted
      // declaration trivial.
      if (!content.includes("@ts-nocheck")) {
        content = `// @ts-nocheck\n${content}`;
      }
      if (name === "types.ts") {
        content = content.replace("export default {", "const __typeMapSource: any = {");
        content = content.replace(/\}\s*$/, "};\nexport default __typeMapSource;\n");
      }
      const fileDir = name.includes("/") ? name.slice(0, name.lastIndexOf("/")) : "";
      return [name, fixImportsFor(files)(content, fileDir)];
    })
    .sort(([a], [b]) => a.localeCompare(b));
};

const env = await loadEnv();
const baseUrl = (env.TWENTY_BASE_URL || "").replace(/\/+$/, "");
const apiKey = env.TWENTY_API_KEY || "";
if (!baseUrl || !apiKey) {
  console.error("TWENTY_BASE_URL and TWENTY_API_KEY are required (repo .env.local or env).");
  process.exit(1);
}

const introspect = await fetch(`${baseUrl}/graphql`, {
  method: "POST",
  headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
  body: JSON.stringify({ query: getIntrospectionQuery() }),
});
if (!introspect.ok) {
  console.error(`Introspection failed: HTTP ${introspect.status} ${await introspect.text().catch(() => "")}`);
  process.exit(1);
}
const payload = (await introspect.json());
if (payload.errors?.length) {
  console.error(`Introspection errors: ${JSON.stringify(payload.errors).slice(0, 500)}`);
  process.exit(1);
}
const schema = printSchema(buildClientSchema(payload.data));
console.log(`Introspected schema: ${schema.length} chars`);

const scratch = await mkdtemp(join(tmpdir(), "dialer-client-"));
// Emit the genql client only. No CoreApiClient wrapper: it reads
// process.env at module scope and throws on import in a browser, and each
// consumer authenticates its own way (backend: API key, SPA: operator token).
await generateCoreClientFromSchema({
  schema,
  outputPath: scratch,
  clientWrapperTemplateSource: "",
});
const pairs = [];
await collect(scratch, scratch, pairs);
const emitted = prepare(pairs);
await rm(scratch, { recursive: true, force: true });

if (process.argv.includes("--check")) {
  for (const [name, content] of emitted) {
    if ((await readFile(join(TARGET_DIR, name), "utf8").catch(() => "")) !== content) {
      console.error(`${name} is stale — run \`bun run api:client\` and commit the result.`);
      process.exit(1);
    }
  }
  console.log("Generated client is up to date.");
} else {
  await rm(TARGET_DIR, { recursive: true, force: true });
  for (const [name, content] of emitted) {
    const path = join(TARGET_DIR, name);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  console.log(`Wrote ${emitted.length} files to ${TARGET_DIR}`);
}
